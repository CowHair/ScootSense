import { $, api, md, esc, skeletonText } from './ui.js';

export function initInsights() {
  $('#btn-report').addEventListener('click', generateReport);
}

async function generateReport() {
  const btn = $('#btn-report');
  btn.disabled = true;
  btn.textContent = 'Generating…';
  $('#report').innerHTML = skeletonText(8);
  try {
    const r = await api('/api/ai/report', { method: 'POST', body: { audience: $('#rep-audience').value, focus: $('#rep-focus').value } });
    $('#report').innerHTML = md(r.markdown) +
      `<p class="secondary small">${r.source === 'gemini' ? `Generated by ${esc(r.model)}` : 'Offline summary'}, ${new Date().toLocaleString()}</p>`;
  } catch (e) {
    $('#report').innerHTML = `<p class="secondary">Failed: ${esc(e.message)}</p>`;
  } finally {
    btn.disabled = false;
    btn.textContent = 'Generate';
  }
}
